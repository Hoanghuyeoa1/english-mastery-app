// @vitest-environment happy-dom
import { describe, it, expect, vi, beforeEach } from 'vitest';
import { render, screen, fireEvent } from '@testing-library/react';
import React from 'react';
import { Dashboard } from '../Dashboard';
import { useAppStore } from '../../store/useAppStore';

describe('PHASE 5: Dashboard Integration with Today Learning Plan', () => {
  beforeEach(() => {
    // Reset Zustand store state to known baseline
    useAppStore.setState({
      profile: {
        name: 'Hoang Tester',
        level: 5,
        xp: 1250,
        streak: 12,
        lastActiveDate: '2026-10-06',
        lastStudyDate: '2026-10-06',
        hearts: 5,
        maxHearts: 5,
        avatarSeed: 'Learner',
        targetDailyWords: 15,
        targetDailyNewWords: 15,
        extraNewWordsBonus: 0,
        isOnboarded: true,
        targetGoal: 'daily',
        geminiApiKey: '',
        equippedFrame: null,
        unlockedFrames: [],
      },
      vocabularyList: [
        {
          id: 'card-1',
          word: 'ubiquitous',
          meaning: 'phổ biến khắp nơi',
          ipa: '/juːˈbɪk.wɪ.təs/',
          partOfSpeech: 'adj',
          example: 'Smartphones are ubiquitous nowadays.',
          tag: 'Daily',
          srsLevel: 2,
          nextReviewDate: '2026-10-06T00:00:00.000Z',
          interval: 3,
          easeFactor: 2.5,
        },
      ],
      srsProgressMap: {
        'card-1': {
          srsLevel: 2,
          nextReviewDate: '2026-10-06T00:00:00.000Z',
          interval: 3,
          easeFactor: 2.5,
        },
      },
      mistakeBank: {},
      dailyHistory: {
        '2026-10-06': {
          date: '2026-10-06',
          wordsReviewed: 0,
          newWordsLearned: 0,
          quizzesCompleted: 0,
          pronunciationsMastered: 0,
          xpGained: 50,
        },
      },
    });
  });

  it('renders Today Learning Plan as the primary focus section', () => {
    const onNavigate = vi.fn();
    const onOpenAddWord = vi.fn();

    render(<Dashboard onNavigate={onNavigate} onOpenAddWord={onOpenAddWord} />);

    // Primary Today Learning Plan widget heading and badge
    expect(screen.getByText('Kế Hoạch Hôm Nay')).toBeDefined();
    expect(screen.getByText('Trọng Tâm Học Tập Ngày')).toBeDefined();

    // Must render the due SRS card generated by todayLearningPlanService
    expect(screen.getAllByText(/Ôn tập 1 thẻ Flashcard đến hạn/i).length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText('Ưu tiên cao')).toBeDefined();
  });

  it('preserves existing secondary statistics and features', () => {
    const onNavigate = vi.fn();
    const onOpenAddWord = vi.fn();

    render(<Dashboard onNavigate={onNavigate} onOpenAddWord={onOpenAddWord} />);

    // 1. Mythic Hero Banner & User Rank / Streak
    expect(screen.getAllByText(/Hoang Tester/i).length).toBeGreaterThanOrEqual(1);
    expect(screen.getByText(/12 ngày liên tục/i)).toBeDefined();

    // 2. 4 Quick Performance Counter Badges
    expect(screen.getByText('Cần ôn hôm nay')).toBeDefined();
    expect(screen.getByText('Từ mới hôm nay')).toBeDefined();
    expect(screen.getByText('XP kiếm được hôm nay')).toBeDefined();
    expect(screen.getByText('Chuỗi Streak')).toBeDefined();

    // 3. Daily Quests & Rương Báu
    expect(screen.getByText('Nhiệm Vụ Ngày & Rương Báu Hoàng Gia')).toBeDefined();
    expect(screen.getByText(/Rương Báu Ngày/i)).toBeDefined();

    // 4. Four Skills Competency Radar
    expect(screen.getByText('Năng Lực 4 Kỹ Năng')).toBeDefined();

    // 5. Mini Achievements Widget
    expect(screen.getByText('Thành Tựu & Danh Hiệu')).toBeDefined();
  });

  it('dispatches CTA navigation when clicking action inside Today Learning Plan', () => {
    const onNavigate = vi.fn();
    const onOpenAddWord = vi.fn();

    render(<Dashboard onNavigate={onNavigate} onOpenAddWord={onOpenAddWord} />);

    const startButton = screen.getByRole('button', { name: /Bắt đầu nhiệm vụ Ôn tập 1 thẻ/i });
    expect(startButton).toBeDefined();

    fireEvent.click(startButton);
    expect(onNavigate).toHaveBeenCalledWith('flashcards');
  });
});
