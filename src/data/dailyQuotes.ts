export function getDailyQuote(dateStr?: string): DailyQuote {
  const targetDate = dateStr ? new Date(dateStr) : new Date();
  const startOfYear = new Date(targetDate.getFullYear(), 0, 0);
  const diff = targetDate.getTime() - startOfYear.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay);
  return DAILY_QUOTES[Math.abs(dayOfYear) % DAILY_QUOTES.length];
}
